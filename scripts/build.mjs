#!/usr/bin/env node
// MacroFlow Build Pipeline:
// 1. Compiles `crates/macroflow-core` (Rust) -> `pkg/macroflow_core.wasm`
// 2. Embeds the Wasm binary into `src/wasm-bytes.ts` for synchronous offline instantiation
// 3. Type-checks and compiles `src/*.ts` -> `dist/app.js` and `src/sw.ts` -> `sw.js`

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));
const wasmOnly = args.has('--wasm-only');
const tsOnly = args.has('--ts-only');

const cargoHomeBin = path.join(process.env.USERPROFILE || process.env.HOME || '', '.cargo', 'bin');
const env = {
    ...process.env,
    PATH: cargoHomeBin ? `${cargoHomeBin}${path.delimiter}${process.env.PATH || ''}` : process.env.PATH
};

if (!tsOnly) {
    console.log('[1/3] Compiling Rust core engine (crates/macroflow-core -> wasm32-unknown-unknown)...');
    execSync(
        'cargo build --manifest-path crates/macroflow-core/Cargo.toml --target wasm32-unknown-unknown --release',
        { cwd: rootDir, env, stdio: 'inherit' }
    );

    const builtWasm = path.join(
        rootDir,
        'crates',
        'macroflow-core',
        'target',
        'wasm32-unknown-unknown',
        'release',
        'macroflow_core.wasm'
    );
    const pkgDir = path.join(rootDir, 'pkg');
    fs.mkdirSync(pkgDir, { recursive: true });
    const destWasm = path.join(pkgDir, 'macroflow_core.wasm');
    fs.copyFileSync(builtWasm, destWasm);
    console.log(`      Copied ${destWasm} (${fs.statSync(destWasm).size} bytes)`);
}

const wasmPath = path.join(rootDir, 'pkg', 'macroflow_core.wasm');
if (!fs.existsSync(wasmPath)) {
    throw new Error(`Missing ${wasmPath}. Run without --ts-only first.`);
}

console.log('[2/3] Generating src/wasm-bytes.ts from pkg/macroflow_core.wasm...');
const wasmBase64 = fs.readFileSync(wasmPath).toString('base64');
const wasmBytesTs = `// AUTO-GENERATED BY scripts/build.mjs — DO NOT EDIT MANUALLY
// Contains the compiled Rust WebAssembly module (pkg/macroflow_core.wasm).
const MACROFLOW_WASM_BASE64: string = "${wasmBase64}";
`;
fs.mkdirSync(path.join(rootDir, 'src'), { recursive: true });
fs.writeFileSync(path.join(rootDir, 'src', 'wasm-bytes.ts'), wasmBytesTs, 'utf8');

if (!wasmOnly) {
    console.log('[3/3] Compiling TypeScript (src/*.ts -> dist/app.js, src/sw.ts -> sw.js)...');
    const tscBin = path.join(rootDir, 'node_modules', 'typescript', 'bin', 'tsc');
    execSync(`node "${tscBin}" -p tsconfig.json`, { cwd: rootDir, env, stdio: 'inherit' });
    execSync(`node "${tscBin}" -p tsconfig.sw.json`, { cwd: rootDir, env, stdio: 'inherit' });
    console.log('Build complete!');
}
