#[derive(Debug, Clone)]
pub struct StapleFoodSpec {
    pub name: &'static str,
    pub calories: i64,
    pub protein: f64,
    pub carbs: f64,
    pub fats: f64,
    pub serving_size: f64,
    pub serving_unit: &'static str,
    pub food_type: &'static str,
    pub store: &'static str,
    pub micros: &'static [(&'static str, f64)],
}

impl StapleFoodSpec {
    pub fn to_enriched_value(&self) -> Value {
        let mut micros_map = Map::new();
        for def in MICRONUTRIENT_DEFS.iter() {
            micros_map.insert(def.id.to_string(), Value::Number(Number(0.0)));
        }
        for (k, v) in self.micros {
            micros_map.insert((*k).to_string(), Value::Number(Number(*v)));
        }
        let mut f = Map::new();
        f.insert("name".to_string(), Value::String(self.name.to_string()));
        f.insert("calories".to_string(), Value::Number(Number(self.calories as f64)));
        f.insert("protein".to_string(), Value::Number(Number(self.protein)));
        f.insert("carbs".to_string(), Value::Number(Number(self.carbs)));
        f.insert("fats".to_string(), Value::Number(Number(self.fats)));
        f.insert("servingSize".to_string(), Value::Number(Number(self.serving_size)));
        f.insert("servingUnit".to_string(), Value::String(self.serving_unit.to_string()));
        f.insert("type".to_string(), Value::String(self.food_type.to_string()));
        f.insert("store".to_string(), Value::String(self.store.to_string()));
        f.insert("micros".to_string(), Value::Object(micros_map));
        Value::Object(f)
    }
}

