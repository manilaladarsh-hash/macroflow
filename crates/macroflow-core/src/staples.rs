// Moves all micronutrient metadata, upper limits, RDA profiles, and staple food records into Rust.

use crate::json::{Map, Number, Value};

#[derive(Debug, Clone)]
pub struct MicronutrientDef {
    pub id: &'static str,
    pub name: &'static str,
    pub unit: &'static str,
    pub category: &'static str,
    pub target_key: &'static str,
    pub color: &'static str,
    pub is_limit: bool,
}

impl MicronutrientDef {
    pub fn to_value(&self) -> Value {
        let mut m = Map::new();
        m.insert("id".to_string(), Value::String(self.id.to_string()));
        m.insert("name".to_string(), Value::String(self.name.to_string()));
        m.insert("unit".to_string(), Value::String(self.unit.to_string()));
        m.insert("category".to_string(), Value::String(self.category.to_string()));
        m.insert("targetKey".to_string(), Value::String(self.target_key.to_string()));
        m.insert("color".to_string(), Value::String(self.color.to_string()));
        if self.is_limit {
            m.insert("isLimit".to_string(), Value::Bool(true));
        }
        Value::Object(m)
    }
}

